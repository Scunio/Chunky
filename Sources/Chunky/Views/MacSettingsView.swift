#if os(macOS)
import SwiftUI

/// macOS Preferences: category sidebar + detail panel, like System Settings.app
/// on macOS Ventura+, instead of the single long, navigable `Form` used by `SettingsView` (that
/// one stays for iOS, where it's the correct pattern). Each category shows all of its own content
/// with no further navigation: macOS's HIG doesn't call for a back button inside
/// Preferences.
///
/// We don't use an icon-based `TabView` (the "classic Preferences" style of Mail/Safari/Xcode):
/// when it's the direct content of `Settings`, macOS produces a fixed-size panel
/// that ignores `.windowResizability` — verified live, zooming and manually resizing had
/// no effect at all. The sidebar is a regular window, so it stays resizable.
struct MacSettingsView: View {
    private enum Category: String, CaseIterable, Identifiable {
        case reading, navigation, imageQuality, appearance, language, library, parentalLock, diagnostics, info

        var id: String { rawValue }

        var title: String {
            switch self {
            case .reading: AppLocalization.localizedString("Lettura", comment: "Settings category")
            case .navigation: AppLocalization.localizedString("Navigazione", comment: "Settings category")
            case .appearance: AppLocalization.localizedString("Colori", comment: "Settings category")
            case .imageQuality: AppLocalization.localizedString("Qualità immagine", comment: "Settings category")
            case .parentalLock: AppLocalization.localizedString("Blocco genitori", comment: "Settings category")
            case .library: AppLocalization.localizedString("Libreria e sincronizzazione", comment: "Settings category")
            case .diagnostics: AppLocalization.localizedString("Diagnostica", comment: "Settings category")
            case .language: AppLocalization.localizedString("Lingua", comment: "Settings category")
            case .info: AppLocalization.localizedString("Informazioni", comment: "Settings category")
            }
        }

        var systemImage: String {
            switch self {
            case .reading: "book"
            case .navigation: "cursorarrow.click"
            case .appearance: "paintpalette"
            case .imageQuality: "wand.and.stars"
            case .parentalLock: "lock"
            case .library: "books.vertical"
            case .diagnostics: "stethoscope"
            case .language: "globe"
            case .info: "info.circle"
            }
        }
    }

    /// Sidebar groups, in display order: everyday reading first, support last — Diagnostica is a
    /// tool for when something goes wrong, not a preference among the others.
    private static let groups: [(title: String, categories: [Category])] = [
        (AppLocalization.localizedString("Lettura", comment: "Settings group"), [.reading, .navigation, .imageQuality]),
        (AppLocalization.localizedString("Aspetto", comment: "Settings group"), [.appearance, .language]),
        (AppLocalization.localizedString("Libreria", comment: "Settings group"), [.library]),
        (AppLocalization.localizedString("Privacy", comment: "Settings group"), [.parentalLock]),
        (AppLocalization.localizedString("Supporto", comment: "Settings group"), [.diagnostics, .info])
    ]

    @State private var selection: Category? = .reading

    var body: some View {
        NavigationSplitView {
            List(selection: $selection) {
                ForEach(Self.groups, id: \.title) { group in
                    Section(group.title) {
                        ForEach(group.categories) { category in
                            Label(category.title, systemImage: category.systemImage)
                                .tag(category)
                        }
                    }
                }
            }
            .navigationSplitViewColumnWidth(min: 160, ideal: 180, max: 220)
        } detail: {
            content(for: selection ?? .reading)
                .navigationTitle((selection ?? .reading).title)
                // Minimum width for the detail panel alone: without this, rows with
                // wide controls (e.g. "Accent color" with its ColorPicker) overflow
                // and get clipped by the column edge when the window is narrow
                // (verified live).
                .frame(minWidth: 420)
        }
        .navigationSplitViewStyle(.balanced)
        // The button to collapse the sidebar is generated by the system (by the NSSplitViewController
        // underneath NavigationSplitView), the exact same control as Mail/Notes/Finder — it isn't
        // removable with public APIs, and attempts to place something else next to it in the toolbar
        // (tried live) only made it more misaligned. We leave it: for a Mac user
        // it's a recognizable native element, not a flaw in this window.
        .frame(minWidth: 680, idealWidth: 760, minHeight: 460, idealHeight: 640)
    }

    @ViewBuilder
    private func content(for category: Category) -> some View {
        switch category {
        case .reading: ReadingSettingsTab()
        case .navigation: NavigationSettingsTab()
        case .appearance: ColorThemeView()
        case .imageQuality: ImageQualitySettingsTab()
        case .parentalLock: ParentalLockSettingsTab()
        case .library: LibrarySettingsTab()
        case .diagnostics: DiagnosticsSettingsTab()
        case .language: AppLanguageSettings()
        case .info: InfoSettingsTab()
        }
    }
}

private struct ReadingSettingsTab: View {
    @AppStorage("defaultReadingDirection") private var defaultReadingDirectionRawValue = ReadingDirection.leftToRight.rawValue
    @AppStorage("doublePageMode") private var isDoublePageEnabled = false
    @AppStorage("doublePageAutoMode") private var isDoublePageAutoMode = true
    @AppStorage("doublePageCoverAlone") private var isCoverAlone = true
    @AppStorage("singlePageZoomMode") private var singlePageZoomMode = PageZoomMode.fitPage
    @AppStorage("doublePageZoomMode") private var doublePageZoomMode = PageZoomMode.fitPage

    private var defaultReadingDirection: Binding<ReadingDirection> {
        Binding(
            get: { ReadingDirection(rawValue: defaultReadingDirectionRawValue) ?? .leftToRight },
            set: { defaultReadingDirectionRawValue = $0.rawValue }
        )
    }

    var body: some View {
        Form {
            Section(
                header: Text("Lettura"),
                footer: Text("La direzione predefinita si applica ai nuovi fumetti importati. Puoi comunque cambiarla per ogni fumetto dal lettore.")
            ) {
                Picker("Direzione predefinita", selection: defaultReadingDirection) {
                    ForEach(ReadingDirection.allCases) { direction in
                        Text(direction.label).tag(direction)
                    }
                }
                Picker("Pagine", selection: PageLayoutChoice.binding(autoMode: $isDoublePageAutoMode, doublePage: $isDoublePageEnabled)) {
                    ForEach(PageLayoutChoice.allCases) { choice in
                        Text(choice.label).tag(choice)
                    }
                }
                Toggle(isOn: $isCoverAlone) {
                    infoLabel("Copertina da sola", info: "In doppia pagina, mostra sempre la prima pagina (di solito la copertina) da sola invece che affiancata alla seconda. L'accoppiamento a due pagine riprende dalla seconda pagina in poi.")
                }
            }

            Section(
                header: Text("Zoom"),
                footer: Text("\"Adatta pagina\" mostra sempre l'intera pagina. \"Adatta larghezza\" scala alla larghezza dello schermo e rende la pagina scorrevole verticalmente se più alta dello schermo.")
            ) {
                Picker("Pagine singole", selection: $singlePageZoomMode) {
                    ForEach(PageZoomMode.allCases) { mode in
                        Text(mode.label).tag(mode)
                    }
                }
                Picker("Pagine doppie", selection: $doublePageZoomMode) {
                    ForEach(PageZoomMode.allCases) { mode in
                        Text(mode.label).tag(mode)
                    }
                }
            }
        }
        .formStyle(.grouped)
    }
}

private struct NavigationSettingsTab: View {
    @AppStorage("tapPageTurnStyle") private var tapPageTurnStyle = TapPageTurnStyle.slide
    @AppStorage("swipePageTurnStyle") private var swipePageTurnStyle = TapPageTurnStyle.slide
    @AppStorage("tapToPanEnabled") private var isTapToPanEnabled = false
    @AppStorage("hotCornersEnabled") private var isHotCornersEnabled = false

    var body: some View {
        Form {
            Section(header: Text("Navigazione")) {
                // Mac wording (click, not tap/thumb), and no "one-handed mode": a thumb
                // affordance for phones that the Mac reader doesn't apply.
                Toggle(isOn: $isTapToPanEnabled) {
                    infoLabel("Avanza sempre al clic", info: "Facendo clic su un bordo qualsiasi della pagina si va sempre avanti, invece che indietro o avanti a seconda del lato.")
                }
                .disabled(tapPageTurnStyle == .disabled)
                Toggle(isOn: $isHotCornersEnabled) {
                    infoLabel("Angoli attivi", info: "Angoli per raggiungere velocemente alcuni controlli comuni senza richiamare i controlli. Fai clic nell'angolo in alto a sinistra per uscire dalla lettura, in alto a destra per le impostazioni, in basso a destra per alternare la doppia pagina.")
                }
                .disabled(tapPageTurnStyle == .disabled)
                Picker("Cambio pagina al clic", selection: $tapPageTurnStyle) {
                    ForEach(TapPageTurnStyle.allCases) { style in
                        Text(style.label).tag(style)
                    }
                }
                Picker("Cambio pagina con scorrimento", selection: $swipePageTurnStyle) {
                    ForEach(TapPageTurnStyle.allCases) { style in
                        Text(style.label).tag(style)
                    }
                }
            }

        }
        .formStyle(.grouped)
    }
}

private struct ImageQualitySettingsTab: View {
    @AppStorage("autoCropEnabled") private var isAutoCropEnabled = false
    @AppStorage("upscalingEnabled") private var isUpscalingEnabled = false
    @AppStorage("autoTintContrastEnabled") private var isAutoTintContrastEnabled = false

    var body: some View {
        Form {
            Section(
                header: Text("Qualità immagine")
            ) {
                Toggle(isOn: $isAutoCropEnabled) {
                    infoLabel("Ritaglia bordi bianchi", info: "Ritaglia i margini bianchi dei fumetti per sfruttare al meglio lo spazio sullo schermo.")
                }
                Toggle(isOn: $isAutoTintContrastEnabled) {
                    infoLabel("Tinta e contrasto automatici", info: "Corregge pagine ingiallite e inchiostro sbiadito. Lascialo disattivato per fumetti già di buona qualità.")
                }
                Toggle(isOn: $isUpscalingEnabled) {
                    infoLabel("Upscaling pagine a bassa risoluzione", info: "Ingrandisce le pagine a bassa risoluzione con un filtro di qualità invece del semplice ridimensionamento, per tavole più nitide.")
                }
            }
        }
        .formStyle(.grouped)
    }
}

private struct ParentalLockSettingsTab: View {
